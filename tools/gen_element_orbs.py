def render(name: str, rows: list[str], palette: list[str]) -> Image.Image:
    assert len(rows) == 16, f"{name}: 需要 16 行，实际 {len(rows)}"
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == 16, f"{name} 第 {y} 行长度 {len(row)} != 16"
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            color = palette[int(ch) - 1]
            r = int(color[1:3], 16)
            g = int(color[3:5], 16)
            b = int(color[5:7], 16)
            px[x, y] = (r, g, b, 255)
    return img


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    images = {}
    for name, rows in SPRITES.items():
        img = render(name, rows, PALETTES[name])
        img.save(OUT / f"{name}.png")
        images[name] = img
        print("ok", name)

    # 8 倍最近邻图板
    scale, pad, label_h = 8, 6, 10
    names = list(SPRITES)
    cols = 5
    rows_n = (len(names) + cols - 1) // cols
    cell = 16 * scale + pad * 2
    board = Image.new("RGBA", (cols * cell, rows_n * (cell + label_h)), (24, 24, 28, 255))
    for i, name in enumerate(names):
        cx = (i % cols) * cell + pad
        cy = (i // cols) * (cell + label_h) + pad
        big = images[name].resize((16 * scale, 16 * scale), Image.Resampling.NEAREST)
        board.alpha_composite(big, (cx, cy))
    board.save(OUT / "preview-8x.png")
    print("preview ->", OUT / "preview-8x.png")


if __name__ == "__main__":
    main()
